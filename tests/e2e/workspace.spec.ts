import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('私人账本只保留基础账户，登录、外观、侧栏与退出正常', async ({ page, request }) => {
  expect((await request.get('http://localhost:8080/api/health')).ok()).toBeTruthy();
  const email = `private-${randomUUID()}@example.test`;
  const password = `Test-${randomUUID()}!`;
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: '注册账号', exact: true }).click();
  await expect(page.getByLabel(/^昵称/)).toHaveCount(0);
  await page.getByLabel(/^邮箱/).fill(email);
  await page.getByLabel(/^密码/).fill(password);
  await page.getByLabel(/^确认密码/).fill(password);
  const registered = page.waitForResponse(response => response.url().endsWith('/api/auth/register') && response.request().method() === 'POST');
  await page.getByRole('button', { name: '注册' }).click();
  const session = await (await registered).json();
  expect(Object.keys(session.user).sort()).toEqual(['created_at', 'email', 'id']);
  const headers = { Authorization: `Bearer ${session.token}` };
  const me = await (await request.get('http://localhost:8080/api/me', { headers })).json();
  expect(Object.keys(me).sort()).toEqual(['created_at', 'email', 'id']);
  expect(me.email).toBe(email);
  expect((await request.patch('http://localhost:8080/api/me', { headers, data: { bio: 'removed' } })).status()).toBe(405);
  await expect(page.getByRole('heading', { name: '老板账本', exact: true })).toBeVisible();
  const navigation = page.getByRole('navigation', { name: '主导航' });
  await expect(navigation.getByRole('button')).toHaveCount(2);
  for (const name of ['工具箱', '个人资料', '快速切换', '搜索页面与工具', '战绩记录']) {
    await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0);
  }
  await expect(page.getByText('工作空间已就绪', { exact: true })).toHaveCount(0);
  await expect(page.getByText('准备好，开始下一场。', { exact: true })).toHaveCount(0);
  await page.keyboard.press('Control+k');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: '收起侧栏', exact: true }).click();
  await expect(page.locator('.sidebar')).toHaveClass(/collapsed/);
  await navigation.getByRole('button', { name: '设置', exact: true }).click();
  await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '展开侧栏', exact: true }).click();
  await expect(page.locator('.sidebar')).not.toHaveClass(/collapsed/);
  await navigation.getByRole('button', { name: '设置', exact: true }).click();
  await expect(page.getByText(email, { exact: true }).first()).toBeVisible();
  await expect(page.getByLabel('个人简介')).toHaveCount(0);
  await expect(page.getByRole('combobox', { name: '陪玩状态', exact: true })).toHaveCount(0);
  await page.locator('label').filter({ hasText: '浅色' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await navigation.getByRole('button', { name: '老板账本', exact: true }).click();
  expect(await page.locator('.page-transition').evaluate(element => getComputedStyle(element).animationName)).toBe('none');
  await navigation.getByRole('button', { name: '设置', exact: true }).click();
  await page.locator('label').filter({ hasText: '深色' }).click();
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '登录', exact: true })).toBeVisible();
  await page.getByLabel(/^邮箱/).fill(email);
  await page.getByLabel(/^密码/).fill('Incorrect-password-2026');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByText('邮箱或密码不正确，请重新输入', { exact: true })).toBeVisible();
  await page.getByLabel(/^密码/).fill(password);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '老板账本', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '账号菜单', exact: true }).click();
  await page.getByRole('menuitem', { name: '退出登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '登录', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
