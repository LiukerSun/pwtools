import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import type { Boss, ServiceOrder } from '../../apps/desktop/src/shared/contracts';
import { addBoss, confirmRound, createOrder, openLedger, openRound, orderArticle } from './ledger-helpers';

test('先选老板再记场，多老板多订单独立记账，保存和取消留在原订单', async ({ page }) => {
  test.setTimeout(120_000);
  const ledger = await openLedger(page);
  await expect(page.getByRole('button', { name: '新建订单', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '记一场', exact: true })).toHaveCount(0);
  const a = await addBoss(page, '小桃老板');
  const hourly = await createOrder(page, '周末陪玩', 'hourly', async form => { await form.getByLabel('约定陪玩时长小时', { exact: true }).fill('2'); });
  const escort = await createOrder(page, '航天护航', 'escort', async form => { await form.getByLabel(/^约定带出金额/).fill('10000000'); });
  const second = await createOrder(page, '基地补充护航', 'escort', async form => { await form.getByLabel(/^约定带出金额/).fill('5000000'); });
  let form = await openRound(page, hourly.title);
  await expect(form.getByRole('combobox', { name: /^所属/ })).toHaveCount(0);
  await form.getByLabel('本次陪玩时长分钟', { exact: true }).fill('45');
  await confirmRound(page, form);
  await expect(orderArticle(page, hourly.title)).toContainText('1 小时 15 分钟');
  form = await openRound(page, escort.title);
  await form.getByLabel(/^带出金额/).fill('3500000');
  await form.getByLabel(/^假账扣除/).fill('500000');
  await confirmRound(page, form);
  await expect(orderArticle(page, escort.title)).toContainText('7,000,000');
  await ledger.post(`/orders/${escort.id}/entries`, { kind: 'progress', quantity: 0, amount: 0, fake_amount: 0, outcome: 'failed', failure_extra_amount: 1000000, occurred_at: null, note: '失败追加 100 万，删除只影响本单。', idempotency_key: randomUUID() });
  await ledger.post(`/orders/${second.id}/entries`, { kind: 'progress', quantity: 1000000, amount: 1000000, fake_amount: 0, outcome: 'success', failure_extra_amount: 0, occurred_at: null, note: '第二单独立计入。', idempotency_key: randomUUID() });
  await page.getByRole('button', { name: '刷新老板订单', exact: true }).click();
  await expect(orderArticle(page, escort.title)).toContainText('8,000,000');
  await expect(orderArticle(page, second.title)).toContainText('4,000,000');
  await page.getByRole('button', { name: '返回所有老板', exact: true }).click();
  await expect(page.getByRole('row', { name: '小桃老板老板汇总', exact: true })).toContainText('12,000,000');
  const b = await addBoss(page, '团团老板', '团团吃大饼');
  const other = await createOrder(page, '团团专属护航', 'escort', async dialog => { await dialog.getByLabel(/^约定带出金额/).fill('2000000'); });
  form = await openRound(page, other.title);
  await form.getByLabel(/^带出金额/).fill('500000');
  await form.getByRole('button', { name: '无假账，填 0', exact: true }).click();
  await confirmRound(page, form);
  expect((await ledger.get<ServiceOrder>(`/orders/${other.id}`)).remaining_quantity).toBe(1500000);
  expect((await ledger.get<Boss>(`/bosses/${a.id}`)).remaining_amount).toBe(12000000);
  expect((await ledger.get<Boss>(`/bosses/${b.id}`)).remaining_amount).toBe(1500000);
  expect((await ledger.get<ServiceOrder>(`/orders/${hourly.id}`)).remaining_quantity).toBe(75);
  await page.getByRole('button', { name: '返回所有老板', exact: true }).click();
  await page.getByRole('button', { name: '查看小桃老板订单', exact: true }).click();
  const article = orderArticle(page, escort.title);
  await article.getByRole('button', { name: `${escort.title}场次账本`, exact: true }).click();
  await article.locator('.ledger-entry').filter({ hasText: '失败追加 100 万，删除只影响本单。' }).getByRole('button', { name: /^删除/ }).click();
  const deletion = page.getByRole('dialog', { name: '删除这条手工记录？', exact: true });
  await deletion.getByRole('button', { name: '删除记录', exact: true }).click();
  await expect(article).toContainText('7,000,000');
  expect((await ledger.get<ServiceOrder>(`/orders/${second.id}`)).remaining_quantity).toBe(4000000);
  expect((await ledger.get<ServiceOrder>(`/orders/${other.id}`)).remaining_quantity).toBe(1500000);
  form = await openRound(page, escort.title);
  await form.getByLabel(/^带出金额/).fill('420');
  await page.getByRole('navigation').getByRole('button', { name: '设置', exact: true }).evaluate((element: HTMLButtonElement) => element.click());
  const guard = page.getByRole('dialog', { name: '尚有未保存修改', exact: true });
  await expect(guard).toBeVisible();
  await guard.getByRole('button', { name: '继续填写', exact: true }).click();
  await expect(form.getByLabel(/^带出金额/)).toHaveValue('420');
  expect(ledger.errors).toEqual([]);
});
