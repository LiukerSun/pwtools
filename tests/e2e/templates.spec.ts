import { expect, test } from '@playwright/test';
import type { OrderTemplate, ServiceOrder } from '../../apps/desktop/src/shared/contracts';
import { addBoss, createOrder, openLedger, openOrderAction, selectOption, orderArticle } from './ledger-helpers';

test('个人模板保存完整默认值，复制开单可改数值，模板编辑删除不影响旧单', async ({ page }) => {
  test.setTimeout(120_000);
  const ledger = await openLedger(page);
  await addBoss(page, '模板老板');
  const original = await createOrder(page, '常用两小时陪玩', 'hourly', async dialog => {
    await dialog.getByLabel('约定陪玩时长小时', { exact: true }).fill('2');
    await dialog.getByRole('button', { name: /^高级约定与备注/ }).click();
    await dialog.getByLabel(/^订单备注/).fill('模板保存的常用约定。');
  });
  await openOrderAction(page, original.title, '保存为个人模板');
  const save = page.getByRole('dialog', { name: '保存为个人模板', exact: true });
  await save.getByLabel(/^模板名称/).fill('周末两小时');
  const saved = page.waitForResponse(response => response.url().endsWith('/api/order-templates') && response.request().method() === 'POST');
  await save.getByRole('button', { name: '保存模板', exact: true }).click();
  expect((await saved).status()).toBe(201);
  await expect(save).toHaveCount(0);
  let templates = await ledger.get<{ items: OrderTemplate[] }>('/order-templates');
  expect(templates.items).toHaveLength(1);
  const template = templates.items[0];
  expect(template.target_quantity).toBe(120);
  expect(template.note).toBe('模板保存的常用约定。');
  expect(template).not.toHaveProperty('boss_id');
  await page.getByRole('button', { name: '新建订单', exact: true }).click();
  const create = page.getByRole('dialog', { name: '新建订单', exact: true });
  await selectOption(page, create.getByRole('combobox', { name: '个人模板', exact: true }), /周末两小时/);
  await expect(create.getByLabel('约定陪玩时长小时', { exact: true })).toHaveValue('2');
  await create.getByLabel('约定陪玩时长小时', { exact: true }).fill('3');
  await create.getByLabel(/^订单名称/).fill('本次三小时');
  const copied = page.waitForResponse(response => /\/api\/bosses\/[^/]+\/orders$/.test(response.url()) && response.request().method() === 'POST');
  await create.getByRole('button', { name: '创建订单', exact: true }).click();
  const order: ServiceOrder = await (await copied).json();
  expect(order.target_quantity).toBe(180);
  expect((await ledger.get<{ items: OrderTemplate[] }>('/order-templates')).items[0].target_quantity).toBe(120);
  await expect(orderArticle(page, '本次三小时')).toBeVisible();
  await page.getByRole('button', { name: '新建订单', exact: true }).click();
  await create.getByRole('button', { name: '管理个人模板', exact: true }).click();
  const manager = page.getByRole('dialog', { name: '管理个人模板', exact: true });
  await manager.getByRole('button', { name: '编辑周末两小时模板', exact: true }).click();
  const edit = page.getByRole('dialog', { name: '编辑个人模板', exact: true });
  await edit.getByLabel('约定陪玩时长小时', { exact: true }).fill('4');
  await edit.getByRole('button', { name: '保存模板', exact: true }).click();
  await expect(edit).toHaveCount(0);
  templates = await ledger.get('/order-templates');
  expect(templates.items[0].target_quantity).toBe(240);
  expect((await ledger.get<ServiceOrder>(`/orders/${original.id}`)).target_quantity).toBe(120);
  expect((await ledger.get<ServiceOrder>(`/orders/${order.id}`)).target_quantity).toBe(180);
  await manager.getByRole('button', { name: '删除周末两小时模板', exact: true }).click();
  const deletion = page.getByRole('dialog', { name: '删除个人模板？', exact: true });
  await deletion.getByRole('button', { name: '删除模板', exact: true }).click();
  await expect(deletion).toHaveCount(0);
  expect((await ledger.get<{ items: OrderTemplate[] }>('/order-templates')).items).toHaveLength(0);
  expect((await ledger.get<ServiceOrder>(`/orders/${order.id}`)).target_quantity).toBe(180);
  expect(ledger.errors).toEqual([]);
});
