import { expect, test } from '@playwright/test';
import { openLedger, selectOption } from './ledger-helpers';

test('改枪码录入、属性查询、筛选、编辑、复制和删除', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  const { get, errors } = await openLedger(page);
  await page.getByRole('button', { name: '改枪码管理', exact: true }).click();
  await page.getByRole('button', { name: '添加改枪码', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '添加改枪码', exact: true });
  await dialog.getByLabel(/^改枪码/).fill('6L79CCC0BK4JN1CPUVQAH');
  await dialog.getByLabel(/^武器名称/).fill('汤姆逊冲锋枪');
  await dialog.getByLabel('备注', { exact: true }).fill('测试近战方案');
  const lookup = page.waitForResponse(response => response.url().endsWith('/weapon-build-codes/lookup'));
  await dialog.getByRole('button', { name: '查询属性', exact: true }).click();
  expect((await lookup).status()).toBe(200);
  await expect(dialog.getByRole('button', { name: '保存', exact: true })).toBeEnabled();
  await dialog.getByRole('button', { name: '保存', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  let article = page.getByRole('article', { name: '汤姆逊冲锋枪改枪方案', exact: true });
  await expect(article.getByText('测试近战方案', { exact: true })).toBeVisible();
  await page.screenshot({ path: '.artifacts/build-codes-dark.png', fullPage: true });
  await page.getByRole('button', { name: '切换至浅色', exact: true }).click();
  await page.setViewportSize({ width: 760, height: 880 });
  await page.screenshot({ path: '.artifacts/build-codes-light.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1320, height: 880 });
  await article.getByRole('button', { name: '复制', exact: true }).click();
  await expect(page.getByText('改枪码已复制', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('6L79CCC0BK4JN1CPUVQAH');
  await page.getByRole('textbox', { name: '搜索改枪码', exact: true }).fill('不存在的方案');
  await expect(article).toHaveCount(0);
  await page.getByRole('textbox', { name: '搜索改枪码', exact: true }).fill('近战');
  await expect(article).toBeVisible();
  await selectOption(page, page.getByRole('combobox', { name: '筛选模式', exact: true }), '全面战场');
  await expect(article).toHaveCount(0);
  await selectOption(page, page.getByRole('combobox', { name: '筛选模式', exact: true }), '全部');
  await article.getByRole('button', { name: '编辑汤姆逊冲锋枪', exact: true }).click();
  const edit = page.getByRole('dialog', { name: '编辑改枪码', exact: true });
  await edit.getByLabel('备注', { exact: true }).fill('更新近战备注');
  await edit.getByRole('button', { name: '保存', exact: true }).click();
  await expect(edit).not.toBeVisible();
  await expect(article.getByText('更新近战备注', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '老板账本', exact: true }).click();
  await page.getByRole('button', { name: '改枪码管理', exact: true }).click();
  await expect(article).toBeVisible();
  const email = (await page.getByRole('button', { name: '账号菜单', exact: true }).innerText()).trim();
  const accountId = email.slice('flow-'.length, email.indexOf('@'));
  await page.reload();
  await page.getByLabel(/^邮箱/).fill(email);
  await page.getByLabel(/^密码/).fill(`Test-${accountId}!`);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByRole('button', { name: '改枪码管理', exact: true }).click();
  await expect(article.getByText('更新近战备注', { exact: true })).toBeVisible();
  const result = await get<{ items: { note: string }[] }>('/weapon-build-codes');
  expect(result.items[0].note).toBe('更新近战备注');
  await article.getByRole('button', { name: '删除汤姆逊冲锋枪', exact: true }).click();
  await page.getByRole('dialog', { name: '删除改枪码', exact: true }).getByRole('button', { name: '确认删除', exact: true }).click();
  await expect(article).toHaveCount(0);
  await page.getByRole('textbox', { name: '搜索改枪码', exact: true }).fill('');
  await page.getByRole('button', { name: '添加改枪码', exact: true }).click();
  await dialog.getByLabel(/^改枪码/).fill('PTR-32突击步枪-全面战场-6EIAKTC02U9HU6AC38CQJ');
  await expect(dialog.getByLabel(/^武器名称/)).toHaveValue('PTR-32突击步枪');
  await expect(dialog.getByLabel(/^适用模式/)).toHaveValue('全面战场');
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await expect(page.getByRole('dialog', { name: '放弃未保存修改', exact: true })).toBeVisible();
  await page.getByRole('dialog', { name: '放弃未保存修改', exact: true }).getByRole('button', { name: '放弃修改', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: '老板账本', exact: true }).click();
  expect(errors).toEqual([]);
});
