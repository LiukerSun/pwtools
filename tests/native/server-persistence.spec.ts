import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { basename, join, resolve, sep } from 'node:path';
import type { AppInfo } from '../../apps/desktop/src/shared/contracts';
import { NativeApplication } from './native-helpers';

test('真实原生桥在独立进程及全新客户端目录间同步账号、老板、订单和流水', async ({}, testInfo) => {
  test.setTimeout(180_000);
  const prefix = 'pwtools-native-server-persistence-';
  const writerDirectory = await mkdtemp(join(tmpdir(), `${prefix}writer-`));
  const readerDirectory = await mkdtemp(join(tmpdir(), `${prefix}reader-`));
  const apiUrl = (process.env.PWTOOLS_E2E_API_URL || 'http://localhost:8080/api').replace(/\/$/, '');
  const releaseApiUrl = (await readFile(resolve('deploy/desktop-api-url.txt'), 'utf8')).trim();
  const useEmbeddedApi = apiUrl === releaseApiUrl;
  const id = randomUUID();
  const email = `native-server-persistence-${id}@example.test`;
  const password = `Test-${id}!`;
  const bossName = `原生同步老板-${id.slice(0, 8)}`;
  const bossNote = `老板资料跨全新客户端保存-${id}`;
  const orderTitle = `原生同步小时订单-${id.slice(0, 8)}`;
  const entryNote = `45分钟流水跨独立原生进程保存-${id}`;
  const errors: string[] = [];
  let writer: NativeApplication | undefined;
  let reader: NativeApplication | undefined;
  try {
    writer = await NativeApplication.launch(writerDirectory, useEmbeddedApi ? null : apiUrl);
    const page = writer.page;
    page.on('pageerror', error => errors.push(error.message));
    await expect(page.getByRole('heading', { name: '登录', exact: true })).toBeVisible();
    const runtime = await page.evaluate(() => window.pwtools!.appInfo()) as AppInfo & { runtime?: string };
    const expectedVersion = JSON.parse(await readFile(resolve('apps/desktop/package.json'), 'utf8')).version;
    expect(runtime).toMatchObject({ version: expectedVersion, apiUrl, runtime: 'webview2', persistentSession: true });
    await page.getByRole('button', { name: '注册账号', exact: true }).click();
    await page.getByLabel(/^邮箱/).fill(email);
    await page.getByLabel(/^密码/).fill(password);
    await page.getByLabel(/^确认密码/).fill(password);
    await page.getByRole('button', { name: '注册', exact: true }).click();
    await expect(page.getByRole('heading', { name: '老板账本', exact: true })).toBeVisible();
    const user = await page.evaluate(() => window.pwtools!.me());
    expect(user.email).toBe(email);

    await page.getByRole('button', { name: '添加老板', exact: true }).click();
    const bossForm = page.getByRole('dialog', { name: '添加老板', exact: true });
    await bossForm.getByLabel(/^老板称呼/).fill(bossName);
    await bossForm.getByLabel(/^游戏 ID/).fill(id.slice(0, 8));
    await bossForm.getByLabel(/^截图内昵称/).fill('原生同步昵称');
    await bossForm.getByLabel(/^老板备注/).fill(bossNote);
    await bossForm.getByRole('button', { name: '保存', exact: true }).click();
    await expect(bossForm).toHaveCount(0);
    await expect(page.getByRole('region', { name: '老板详情与订单', exact: true })).toBeVisible();
    const bosses = await page.evaluate(() => window.pwtools!.listBosses());
    expect(bosses.items).toHaveLength(1);
    const boss = bosses.items[0];
    expect(boss).toMatchObject({ display_name: bossName, notes: bossNote });

    await page.getByRole('button', { name: '新建订单', exact: true }).click();
    const orderForm = page.getByRole('dialog', { name: '新建订单', exact: true });
    await orderForm.getByRole('radio', { name: '使用小时单模板', exact: true }).check();
    await orderForm.getByLabel(/^订单名称/).fill(orderTitle);
    await orderForm.getByLabel('约定陪玩时长小时', { exact: true }).fill('2');
    await orderForm.getByRole('button', { name: '创建订单', exact: true }).click();
    await expect(orderForm).toHaveCount(0);
    const article = page.getByRole('article', { name: `${orderTitle}订单`, exact: true });
    await expect(article).toBeVisible();
    const orders = await page.evaluate(bossId => window.pwtools!.listOrders(bossId), boss.id);
    expect(orders.items).toHaveLength(1);
    const order = orders.items[0];
    expect(order).toMatchObject({ title: orderTitle, kind: 'hourly', target_quantity: 120 });
    await article.getByRole('button', { name: '记一场', exact: true }).click();
    const round = page.getByRole('dialog', { name: '记一场', exact: true });
    await round.getByLabel('本次陪玩时长分钟', { exact: true }).fill('45');
    await round.getByText('补充信息', { exact: true }).click();
    await round.getByLabel('备注', { exact: true }).fill(entryNote);
    await round.getByRole('button', { name: '确认入账', exact: true }).click();
    await expect(round).toHaveCount(0);
    await expect(article).toContainText('1 小时 15 分钟');
    const entries = await page.evaluate(orderId => window.pwtools!.listLedgerEntries(orderId), order.id);
    expect(entries.total).toBe(1);
    expect(entries.items).toHaveLength(1);
    expect(entries.items[0]).toMatchObject({ kind: 'progress', quantity: 45, source: 'manual', note: entryNote });
    const template = await page.evaluate(async name => window.pwtools!.createOrderTemplate({ name, title: '原生同步模板小时单', kind: 'hourly', target_quantity: 90, failure_default_quantity: 0, note: '跨客户端保存的模板' }), `原生同步模板-${id}`);

    await writer.close();
    expect(writer.process.exitCode).not.toBeNull();
    writer = undefined;
    expect(await readdir(readerDirectory)).toEqual([]);
    reader = await NativeApplication.launch(readerDirectory, useEmbeddedApi ? null : apiUrl);
    const secondPage = reader.page;
    secondPage.on('pageerror', error => errors.push(error.message));
    await expect(secondPage.getByRole('heading', { name: '登录', exact: true })).toBeVisible();
    await secondPage.getByLabel(/^邮箱/).fill(email);
    await secondPage.getByLabel(/^密码/).fill(password);
    await secondPage.getByRole('button', { name: '登录', exact: true }).click();
    await expect(secondPage.getByRole('heading', { name: '老板账本', exact: true })).toBeVisible();
    expect(await secondPage.evaluate(() => window.pwtools!.me())).toEqual(user);
    expect(await secondPage.evaluate(bossId => window.pwtools!.getBoss(bossId), boss.id)).toMatchObject({ id: boss.id, display_name: bossName, game_id: boss.game_id, game_name: boss.game_name, notes: bossNote, remaining_minutes: 75 });
    expect(await secondPage.evaluate(orderId => window.pwtools!.getOrder(orderId), order.id)).toMatchObject({ id: order.id, boss_id: boss.id, title: orderTitle, kind: 'hourly', target_quantity: 120, completed_quantity: 45, remaining_quantity: 75, record_count: 1 });
    expect(await secondPage.evaluate(orderId => window.pwtools!.listLedgerEntries(orderId), order.id)).toEqual(entries);
    expect((await secondPage.evaluate(() => window.pwtools!.listOrderTemplates())).items).toContainEqual(template);
    await expect(secondPage.getByRole('row', { name: `${bossName}老板汇总`, exact: true })).toContainText(bossNote);
    await secondPage.getByRole('button', { name: `查看${bossName}订单`, exact: true }).click();
    await expect(secondPage.getByRole('region', { name: '老板长期备注', exact: true })).toContainText(bossNote);
    const readArticle = secondPage.getByRole('article', { name: `${orderTitle}订单`, exact: true });
    await expect(readArticle).toContainText('1 小时 15 分钟');
    await readArticle.getByRole('button', { name: `${orderTitle}场次账本`, exact: true }).click();
    await expect(readArticle.locator('.ledger-entry')).toHaveCount(1);
    await expect(readArticle.locator('.ledger-entry')).toContainText(entryNote);
    await expect(readArticle.locator('.ledger-entry')).toContainText('45 分钟');
    await secondPage.getByRole('navigation').getByRole('button', { name: '设置', exact: true }).click();
    const settings = secondPage.locator('.settings-layout');
    await expect(settings.getByRole('heading', { name: '外观', exact: true })).toBeVisible();
    await expect(settings.getByRole('heading', { name: '账号', exact: true })).toBeVisible();
    await expect(settings).toContainText(email);
    await expect(settings.locator('.settings-version')).toHaveText(`PWTools v${expectedVersion}`);
    await expect(settings.getByRole('heading', { name: '连接', exact: true })).toHaveCount(0);
    await expect(settings.getByText('连接信息', { exact: true })).toHaveCount(0);
    await expect(settings.getByRole('button', { name: /重试|检查连接/ })).toHaveCount(0);
    await expect(settings.locator('.service-address, .connection-details')).toHaveCount(0);
    await expect(settings).not.toContainText(apiUrl);
    await settings.locator('label').filter({ hasText: '浅色' }).click();
    await expect(secondPage.locator('html')).toHaveAttribute('data-theme', 'light');
    await settings.locator('label').filter({ hasText: '深色' }).click();
    await expect(secondPage.locator('html')).toHaveAttribute('data-theme', 'dark');
    expect(await secondPage.evaluate(() => Object.keys(localStorage).filter(key => !['pwtools:theme', 'pwtools:sidebar-collapsed'].includes(key)))).toEqual([]);
    expect(errors).toEqual([]);
    const reportPath = testInfo.outputPath('native-server-persistence.json');
    await writeFile(reportPath, JSON.stringify({ runtime: runtime.runtime, version: runtime.version, apiUrl, embeddedApiWithoutOverride: useEmbeddedApi, separateProcessAndProfile: true, userId: user.id, bossId: boss.id, orderId: order.id, entryId: entries.items[0].id, entryMinutes: 45, remainingMinutes: 75, templateId: template.id, settingsConnectionHidden: true, pageErrors: errors }, null, 2));
    await testInfo.attach('native-server-persistence', { path: reportPath, contentType: 'application/json' });
    await secondPage.screenshot({ path: testInfo.outputPath('native-settings.png'), animations: 'disabled' });
  } finally {
    await writer?.close().catch(() => {});
    await reader?.close().catch(() => {});
    const targets = [writerDirectory, readerDirectory];
    for (const directory of targets) {
      const target = resolve(directory).toLowerCase();
      if (!target.startsWith(resolve(tmpdir()).toLowerCase() + sep) || !basename(target).startsWith(prefix)) {
        throw new Error('临时目录范围校验失败，未删除任何目录');
      }
    }
    for (const directory of targets) await rm(directory, { recursive: true, force: true, maxRetries: 10, retryDelay: 300 });
  }
});
